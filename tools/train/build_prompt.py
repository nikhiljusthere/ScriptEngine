#!/usr/bin/env python3
"""Rebuild SECTION F of plan/EXTRACTION_PROCEDURE_V2.md from plan/BIG_REVIEW_PATTERNS.md.

SECTION F is the pattern catalog AS SERVED to the labelling model. It used to be hand-copied,
which is how the prompt and the catalog drifted (four hand-typed links: catalog -> SECTION F ->
label_hints.HINTS -> hardcoded flagger strings). This generator makes the served block derived,
and tests/test_prompt_drift.py fails if the two ever disagree again.

  scriptengine/.venv/bin/python tools/train/build_prompt.py          # rewrite SECTION F
  scriptengine/.venv/bin/python tools/train/build_prompt.py --check  # exit 1 if stale

The 13 lines carrying a fact route (A3, A12, A13, A19, A23, A31, A36, A48, A60, A64, A65, A67,
A71) are rendered as "no <event row>; fact: <route>" — the event ruling first, unchanged.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "plan" / "BIG_REVIEW_PATTERNS.md"
PROMPT = ROOT / "plan" / "EXTRACTION_PROCEDURE_V2.md"
BEGIN, END = "<!-- F:BEGIN (generated by tools/train/build_prompt.py) -->", "<!-- F:END -->"

PREAMBLE = """These are the settled rulings from Claude's hand review of the big windows
(`plan/BIG_REVIEW_PATTERNS.md`). Roughly a quarter of them are also checked mechanically on your
repair turn (`big_flags.check()` fires on about 19 of the 72 codes); the rest are read by you,
and a ruling you break is corrected, so treat every line as binding.

**"no row" always means no row in `events`.** The sentence is still yours to record: write a
`facts` row when both ends are nameable, and when no end is nameable write a `tags` row from
this closed set — `no_doer` (a passive with no "by", an item as the doer, someone tied up with
no captor), `crowd_end` (crowd, species, indefinite or descriptive-group ends), `no_relation`
(stated, but with no legal event AND no legal fact). Where a ruling names a fact route, that
route IS the answer: e.g. A71 sparring -> no `fought`, but `trained` as a fact. An event-layer
ruling never justifies deleting a fact or tag row.

A-patterns: what your row must have been. G/R: structural rules for every row you write."""


def rows():
    out = []
    for line in CATALOG.read_text().splitlines():
        m = re.match(r"^\|\s*([AGR]\.?\d+)\s*\|(.+)\|\s*$", line)
        if not m:
            continue
        code, rest = m.group(1), m.group(2)
        cells = [c.strip() for c in rest.split("|")]
        rule = cells[0] if code[0] in "GR" else (cells[1] if len(cells) > 1 else "")
        rule = re.sub(r"\s+", " ", rule).replace("|", "/").strip()
        if rule:
            out.append(f"- **{code}** — {rule}")
    return out


def block():
    return "\n".join([BEGIN, "", "---", "",
                      "# SECTION F — THE REVIEW PATTERN CATALOG (served to every window)", "",
                      PREAMBLE, ""] + rows() + ["", END])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = PROMPT.read_text()
    want = block()
    if BEGIN in text and END in text:
        head = text.split(BEGIN)[0]
        tail = text.split(END, 1)[1]
        got = text.split(BEGIN)[1].split(END)[0]
    else:  # first run: replace the hand-copied section
        head = text.split("# SECTION F")[0].rstrip() + "\n\n"
        tail = ""
        got = ""
    if got.strip() == want.split(BEGIN)[1].split(END)[0].strip():
        print("SECTION F up to date")
        return
    if a.check:
        print("SECTION F is STALE (run tools/train/build_prompt.py)", file=sys.stderr)
        sys.exit(1)
    PROMPT.write_text(head.rstrip("\n") + "\n\n" + want + ("\n" + tail if tail else ""))
    print(f"SECTION F rebuilt: {len(rows())} patterns")


if __name__ == "__main__":
    main()